"""식품 분류(category/subcategory) 기반 카페인 관련성 3단계 판정.

food_items.caffeine_mg가 NULL일 때 그것을 "확인된 0"으로 볼지, "정보 없음"으로 볼지를
음식의 종류만 보고 결정한다. 값 자체는 보지 않는다 — 값이 쓸 만한지 판단하는 것은
recommendation_model._is_caffeine_missing()의 책임이고, 이 모듈은 "이 종류의 음식에서
카페인이 애초에 의미가 있는가"만 답한다 (두 질문은 서로 독립이며, 판정 시 함께 쓰인다).

식품명 문자열이 아니라 분류 컬럼을 키로 쓰는 이유:
food_search_api.CAFFEINE_KEYWORDS 같은 이름 부분문자열 방식은 실측 데이터에서 양방향으로
틀린다. 카페인 값이 있는 3,546행 기준으로 키워드 미매치 행의 29%가 실제로 카페인을
가지고 있었고(스무디_카라멜 프라페 820mg, 밀크티/버블티, 아이스티 등 키워드 목록에 없는
제품군), 반대로 키워드 매치 행의 12%는 실측 0이었다(초코/말차 등 맛 표현이 붙은 제과).
같은 subcategory 안에서도 `라떼_녹차 라떼 (100g)`는 0mg, `라떼_녹차 라떼 핫(HOT) (473ml)`는
208mg이라 이름만으로는 분리되지 않는다. 반면 분류 축은 훨씬 깨끗하게 갈린다(아래 근거).

── 실측 근거 (mompeace.db, data_source='dish_db_download' 19,495행 기준) ──
카페인이 측정된 카테고리는 정확히 3개뿐이고, 나머지 22개 카테고리 4,456행은 전부 NULL이다
(전 소스 19,514행에서 반례 0건 — test_caffeine_relevance.py에서 회귀 검증).
  - 음료 및 차류        5,776행 중 3,312행 측정
  - 빵 및 과자류        8,600행 중   173행 측정 (166행이 0.0, 최대 20.9mg)
  - 유제품류 및 빙과류     663행 중    61행 측정 ( 52행이 0.0, 최대 135.0mg)

── 티어 정의 ──
NOT_MEASURED: 이 종류의 음식은 카페인을 측정한 적이 없다. NULL은 "없다"는 뜻이 아니라
  "잰 적이 없다"는 뜻이므로, 앱은 이 음식에 대해 카페인을 아예 언급하지 않는다.
CAFFEINE_FREE: NULL을 확인된 0으로 취급해도 되는 식품군. 판정에서 카페인을 0으로 더한다.
CAFFEINE_POSSIBLE: 카페인이 들어 있을 수 있는데 값이 없다. 반드시 사용자에게 알린다.

── 빵 및 과자류를 카테고리 통째로 FREE로 두는 근거 ──
측정된 173행 중 166행(96.0%)이 0.0이고, 0이 아닌 7행도 4.5~20.9mg에 그친다
(티라미수 계열 3건, 스모어 쿠키 계열 3건, 티라미수크림 크로플 1건). 최대값 20.9mg는
1일 기준 200mg의 10% 수준이라, 이 카테고리를 FREE로 오분류했을 때의 비용이 작다.
마카롱 41행은 초코/모카/말차 맛까지 포함해 전부 실측 0.0이었다.

── 유제품류 및 빙과류를 subcategory로 나누는 근거 ──
빵과 달리 여기서는 카페인이 실질적이다. 아포가토 120mg, 티라미수케이크 빙수 135mg처럼
에스프레소가 실제로 들어가는 제품이 있어 하루 기준의 60~68%에 달한다. 그래서 아이스크림·
빙수 계열은 POSSIBLE로 두고, 요구르트·우유·치즈만 FREE로 둔다.

── 목록에 없는 subcategory를 POSSIBLE로 기본 처리하는 근거 ──
음료 및 차류 47개 subcategory 중 15개는 측정 행이 0건이라 근거로 티어를 정할 수 없다.
그 15개에는 액상커피 / 커피(타먹는커피) / 카페라떼 / 아이스 카페라떼 / 두유 카페라떼 /
카페모카 / 아이스 카페모카 / 밀크티처럼 명백히 카페인이 있는 것들이 포함되어 있어,
기본값을 FREE로 두면 이들이 조용히 "확인된 0"이 되어 버린다. 반대 방향의 오분류
(꿀차·수박화채·율무차·레몬청차·딸기넥타·미숫가루(선식)음료 20행이 불필요하게 "정보 없음"으로
표시되는 것)는 안전한 쪽의 실수이므로 감수한다.

주의: subcategory 이름에는 근사 중복이 있다 (미숫가루 vs 미숫가루(선식)음료,
밀크티/버블티 vs 밀크티, 커피 vs 액상커피). 부분문자열 매칭이 아니라 정확 일치로만
조회하며, 목록에 없는 변형은 위 기본값 규칙에 따라 POSSIBLE이 된다.

조회 키가 (category, subcategory) 쌍인 이유: subcategory 이름 `고구마`가 서로 다른 두
카테고리(곡류, 서류 제품 / 찜류)에 동시에 존재하므로 subcategory 단독으로는 키가 될 수 없다.
"""
