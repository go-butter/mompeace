def classify_caffeine_relevance(
    category: Optional[str], subcategory: Optional[str]
) -> str:
    """(category, subcategory)로 카페인 관련성 티어를 판정한다.

    category가 None이거나 알 수 없는 값이면 NOT_MEASURED로 본다. 실제 데이터에서는
    도달하지 않는 경로다 — food_items 19,514행 전부 category가 채워져 있고, 판정 함수에
    들어오는 dict는 항상 `SELECT * FROM food_items` 결과이기 때문이다. 분류 자체를 모르는
    입력에 대해 "카페인 정보가 없다"고 알리는 것은 근거 없는 경고가 되므로, 아무 말도 하지
    않는 쪽(NOT_MEASURED)을 기본값으로 둔다. 반면 측정 대상 카테고리 *안에서* 목록에 없는
    subcategory는 근거가 없더라도 POSSIBLE로 처리한다 (파일 상단 기본값 규칙 참고) —
    두 경우는 "분류를 모른다"와 "분류는 알지만 실측이 없다"로 서로 다른 상황이다.
    """
    if category not in MEASURED_CATEGORIES:
        return TIER_NOT_MEASURED

    if category in FULLY_FREE_CATEGORIES:
        return TIER_CAFFEINE_FREE

    if subcategory in CAFFEINE_FREE_SUBCATEGORIES.get(category, frozenset()):
        return TIER_CAFFEINE_FREE

    if subcategory in CAFFEINE_POSSIBLE_SUBCATEGORIES.get(category, frozenset()):
        return TIER_CAFFEINE_POSSIBLE

    return TIER_CAFFEINE_POSSIBLE
